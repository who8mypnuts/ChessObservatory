"""Zobrist keys (plan Phase 1, step 5).

Keys are 64-bit integers generated by splitmix64 from a fixed seed, so the same
position always has the same key across runs, processes and machines. The board
keeps its key incrementally; :func:`compute_key` is the reference used by tests.

The en-passant contribution is keyed by file only: two positions that differ
only in the rank of an otherwise irrelevant ep square are the same position for
repetition purposes. Whether an ep capture is actually legal is a rules question
answered by move generation, not by the key.
"""

from __future__ import annotations

from typing import Final

from chess_observatory.core.pieces import Color
from chess_observatory.core.position import BoardView
from chess_observatory.core.squares import file_of, squares

MASK64: Final = (1 << 64) - 1
SEED: Final = 0x9E3779B97F4A7C15


def splitmix64(state: int) -> tuple[int, int]:
    """Return ``(next_state, output)`` for the splitmix64 generator."""
    state = (state + SEED) & MASK64
    value = state
    value = ((value ^ (value >> 30)) * 0xBF58476D1CE4E5B9) & MASK64
    value = ((value ^ (value >> 27)) * 0x94D049BB133111EB) & MASK64
    return state, value ^ (value >> 31)


def _generate(count: int, seed: int) -> tuple[int, ...]:
    state = seed
    values: list[int] = []
    for _ in range(count):
        state, value = splitmix64(state)
        values.append(value)
    return tuple(values)


_PIECE_SEED: Final = 0xC0FFEE_1234_5678
_CASTLING_SEED: Final = 0xCA57_1E00_0000_0001
_EP_SEED: Final = 0x00E9_0000_0000_0002
_SIDE_SEED: Final = 0x51DE_0000_0000_0003

PIECE_KEYS: Final = tuple(_generate(64, _PIECE_SEED + index * 0x1000) for index in range(12))
CASTLING_KEYS: Final = _generate(16, _CASTLING_SEED)
EP_FILE_KEYS: Final = _generate(8, _EP_SEED)
SIDE_KEY: Final = _generate(1, _SIDE_SEED)[0]


def compute_key(position: BoardView) -> int:
    """Recompute the key from scratch."""
    key = 0
    for index, board in enumerate(position.bb):
        keys = PIECE_KEYS[index]
        for square in squares(board):
            key ^= keys[int(square)]
    key ^= CASTLING_KEYS[position.castling]
    if position.side is Color.BLACK:
        key ^= SIDE_KEY
    if position.ep is not None:
        key ^= EP_FILE_KEYS[file_of(position.ep)]
    return key


def variant_key(position: BoardView) -> tuple[bool, str]:
    """Cache discriminator for non-standard rules.

    Two positions with the same Zobrist key but different legality relaxations
    must not share an attack map, so the variant note is part of the cache key.
    """
    return position.strict, position.variant_note or ""
